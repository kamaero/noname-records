"""Кандидаты в авторские ремарки внутри уже атрибутированной реплики.

Это подсказка для ручной правки в редакторе (см. бриф remark-picker), а НЕ
автоматический проход в базу — с ним не путать `scripts/split_author_remarks.py`.
Там ошибка молча крадёт текст у диктора, поэтому защиты строгие и при сомнении
не режут вовсе. Здесь каждый кандидат перед применением подтверждает человек
глазами: цена ложного кандидата — один лишний взгляд, а пропущенного — незамеченная
ремарка. Значит калибровка обратная — щедрая, с одним-единственным жёстким
исключением (см. `_is_resumed_reply`).
"""
from __future__ import annotations

import re

from app.services.shared_runtime import is_narrator_name

# `is_placeholder_name` живёт в app.v2.cast_ops, а тот на уровне модуля импортирует
# из app.v2.reader — который импортирует этот модуль. Импорт наверху дал бы цикл
# (reader → remark_candidates → cast_ops → reader), поэтому берём функцию лениво,
# внутри remark_candidates ниже.

# Абзац-реплика: открывается тире и пробелом. Если абзац не начинается репликой,
# внутренние тире в нём — не ремарки (описание сцены, дефисы-переносы и т.п.).
_OPEN_RE = re.compile(r"^\s*[-–—]\s")

# Внутреннее тире слов автора/ремарки: тире сразу после знака препинания (не после
# ЛЮБОГО пробела!) — отличает «— сказал он» от тире-дефиса вроде «кто-то» И от
# обычного внутрипредложенческого тире вроде «кузнецов – люди» (буква, пробел,
# тире — это пунктуация посреди фразы, а не граница слов автора). Круг правок 1:
# пробел в lookbehind был унаследован из scripts/split_author_remarks.py, где он
# искал абзацы-кандидаты ЦЕЛИКОМ и точность границы решала модель; здесь граница —
# это сам результат, поэтому перед тире (с необязательным одним пробелом между
# знаком и тире) должен стоять именно знак препинания. Два альтернативных
# lookbehind фиксированной ширины вместо одного с `\s*` — Python re не умеет
# lookbehind переменной длины.
_INNER_DASH_RE = re.compile(
    r"(?<=[,.!?…])[-–—]\s"       # тире сразу после знака препинания
    r"|(?<=[,.!?…]\s)[-–—]\s"    # или после знака препинания и одного пробела
)

# Круг правок 2: длина сама по себе ничего не доказывает — «- » тоже два символа,
# а голое тире (иногда с пробелом) на стыке двух внутренних тире или перед самым
# концом спана даёт именно такой «кандидат» без единой буквы. Проверка по существу:
# буквы (кириллица или латиница) считаются, а не символы. Порог 3 замерен по всей
# книге (13276 сегментов, действующие атрибуции): между «без единой буквы» (15
# кандидатов — все мусор) и «три буквы и больше» (240 — все осмысленные) не
# нашлось ни одного кандидата с 1-2 буквами, порог ничего не отрезает вслепую.
_MIN_CANDIDATE_LETTERS = 3
_LETTER_RE = re.compile(r"[A-Za-zА-Яа-яЁё]")


def _is_resumed_reply(text: str, dash_pos: int, after_dash_pos: int) -> bool:
    """Единственное исключение из щедрой калибровки: тире идёт СРАЗУ после точки и
    продолжается с ПРОПИСНОЙ буквы — это возобновлённая реплика персонажа после
    авторской вставки, а не сами слова автора. Замер по книге: 2733 таких тире —
    подсветка их превратила бы экран в шум (см. бриф)."""
    before = text[:dash_pos].rstrip()
    if not before or before[-1] != ".":
        return False
    after = text[after_dash_pos:].lstrip()
    return bool(after) and after[0].isupper()


def remark_candidates(text: str, spans: list[dict]) -> list[tuple[int, int]]:
    """Непересекающиеся диапазоны в координатах ВСЕГО текста сегмента — фрагменты,
    похожие на слова автора внутри реплики персонажа.

    `spans` — действующие спаны сегмента (как в `segments_payload`): словари с
    `start`/`end`/`speaker`. Ищем только внутри спанов, чей speaker — не Рассказчик
    и не UNSURE-заглушка: спан Рассказчика и так весь читается им, подсвечивать
    там нечего.
    """
    from app.v2.cast_ops import is_placeholder_name  # ленивый импорт — см. верх файла

    text = text or ""
    if not _OPEN_RE.match(text):
        return []  # абзац не открывается репликой — это не прямая речь вовсе

    out: list[tuple[int, int]] = []
    for span in spans or []:
        speaker = span.get("speaker")
        if is_narrator_name(speaker) or is_placeholder_name(speaker):
            continue
        start = int(span.get("start") or 0)
        end = int(span.get("end") or 0)
        if end <= start:
            continue

        matches = [m for m in _INNER_DASH_RE.finditer(text) if start <= m.start() < end]
        for i, match in enumerate(matches):
            piece_start = match.start()
            piece_end = matches[i + 1].start() if i + 1 < len(matches) else end
            if _is_resumed_reply(text, piece_start, match.end()):
                continue  # возобновлённая реплика — не слова автора, пропускаем
            if piece_start == start and piece_end == end:
                continue  # кандидат совпал бы со всем спаном — отдавать нечего
            if len(_LETTER_RE.findall(text[piece_start:piece_end])) < _MIN_CANDIDATE_LETTERS:
                continue  # меньше трёх букв — голое тире/пунктуация, не текст
            out.append((piece_start, piece_end))

    out.sort()
    return out
