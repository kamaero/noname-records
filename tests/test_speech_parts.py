"""Что из куска разметки актёр обязан произнести, а что — нет.

Примеры повторяют устройство живых случаев из книг (текст свой): ровно на таких
сверка рапортовала ложные пропуски.
"""
from app.services.speech_parts import speech_and_narration


def test_ремарка_внутри_реплики_не_ожидается_от_актёра():
    """Живой случай: сверка ждала весь кусок целиком, актёр прочёл только речь."""
    text = "- …Хотя тот лодочник уехал ещё весной, - поправил сам себя трактирщик. – Сгинул, говорят, он"
    speech, narration = speech_and_narration(text)
    assert "Хотя тот лодочник уехал ещё весной" in speech
    assert "Сгинул, говорят, он" in speech
    assert "поправил сам себя трактирщик" not in speech
    assert any("поправил сам себя трактирщик" in part for part in narration)


def test_чистое_повествование_не_даёт_речи_вовсе():
    """Живой случай: повествование ошибочно приписано персонажу. Актёр прав, что молчал."""
    text = "Мельник подошёл ближе с корзиной и негромко сказал:"
    speech, narration = speech_and_narration(text)
    assert speech == ""
    assert narration == [text]


def test_простая_реплика_остаётся_целиком():
    speech, narration = speech_and_narration("— Проводил твоих друзей,")
    assert speech == "Проводил твоих друзей,"
    assert narration == []


def test_тире_внутри_речи_не_считается_ремаркой():
    """«Париж — столица» это речь, а не авторские слова: перед тире нет знака конца."""
    speech, narration = speech_and_narration("— Париж — столица Франции.")
    assert speech == "Париж — столица Франции."
    assert narration == []


def test_дефис_в_слове_не_разрывает_реплику():
    speech, _ = speech_and_narration("— Кто-то всё-таки пришёл.")
    assert speech == "Кто-то всё-таки пришёл."


def test_ремарка_после_восклицания():
    speech, narration = speech_and_narration("— Идём! — крикнул он. — Скорее.")
    assert speech == "Идём! Скорее."
    assert narration == ["крикнул он."]


def test_пустая_строка_ничего_не_даёт():
    assert speech_and_narration("") == ("", [])
    assert speech_and_narration("   ") == ("", [])


def test_реплика_без_тире_это_продолжение_речи_а_не_повествование():
    """Живой случай: реплика, продолженная следующим абзацем,
    не начинается с тире — но это речь персонажа, а не повествование. Замер по
    всем 60 главам: 607 таких кусков из 609 — живая речь, лишь 2 — повествование
    (и оба кончаются двоеточием, см. тест ниже)."""
    text = "Это же просто. Ни во что не лезть, лишнего не болтать."
    speech, narration = speech_and_narration(text)
    assert speech == text
    assert narration == []


def test_двоеточие_в_конце_куска_без_тире_это_повествование():
    """Живой случай: рассказчик заканчивает свою реплику
    атрибуции двоеточием перед прямой речью персонажа в следующем абзаце — этот
    кусок ошибочно приписан персонажу целиком, и весь он авторский."""
    text = "Кузнец ещё миг глядел исподлобья, а потом вздохнул и пообещал:"
    speech, narration = speech_and_narration(text)
    assert speech == ""
    assert narration == [text]


def test_закрывающая_кавычка_перед_тире_это_не_ремарка():
    """Живой случай: тире после «слова-в-кавычках» — это
    не начало ремарки, а связка «X — это Y» внутри самой речи персонажа.
    В книге на «» перед тире держится только этот паттерн — все 14 случаев в
    тексте оказались связкой, ни один — настоящей ремаркой."""
    text = "— Но «далеко» - понятие растяжимое, туда многое помещается."
    speech, narration = speech_and_narration(text)
    assert speech == text[2:]
    assert narration == []
