/** Текст приглашения в бота — один на «Дикторы» и каст. С ролью и книгой — когда зовём
 *  на конкретную роль того, кто ещё не на связи. Имя студии — из настроек установки. */
export function inviteText(bot: string, studio: string, role?: { role: string; book: string }): string {
  const about = role ? `Мы зовём вас на роль «${role.role}» в книге «${role.book}».\n\n` : "";
  const name = studio.trim() || "Noname Records";
  return (
    `Здравствуйте! Это студия озвучки «${name}».\n\n` +
    about +
    "Роли, тексты для записи и сдача дублей — в нашей рабочей системе. Откройте нашего бота и нажмите «Запустить» (Start):\n" +
    `https://t.me/${bot}?start=dictor\n\n` +
    "Бот ответит, что вы на связи, и пришлёт ссылку на сайт. Войти можно через Telegram, пароль не нужен. " +
    "Если вход через Telegram не сработает, нажмите в боте кнопку «🔑 Логин и пароль».\n\n" +
    "Потом в этом же боте будут приходить утверждения на роли и реплики, которые нужно перезаписать."
  );
}
